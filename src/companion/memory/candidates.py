"""Trusted-side handling of model-proposed memory candidates.

The model may repeat itself: a single analysis can contain two candidates whose
content differs only in whitespace or letter case, and a retried request can
propose the same statement again. Candidate rows are *not* long-term memory —
they are inert proposals that only a later, human-confirmed step could ever
promote — but duplicated rows still make the review queue noisy.

Deduplication is therefore done here, on the trusted side, using a normalised
form of the content. This module never talks to the model and never promotes a
candidate to ``ACTIVE``.
"""

from __future__ import annotations

from typing import Iterable, TypeVar

from companion.domain.enums import AssertionType
from companion.domain.models import MemoryCandidate, UtteranceEvent, new_id

T = TypeVar("T")


def normalize_candidate_content(text: str) -> str:
    """Collapse whitespace and case so trivial variants compare equal."""
    return " ".join(str(text).split()).strip().casefold()


def dedupe_candidates(candidates: Iterable[T]) -> list[T]:
    """Drop blank and duplicate candidates, preserving first-seen order.

    Duplicates are compared by normalised ``content`` only; two proposals with
    the same text are the same proposal regardless of which generation produced
    them.
    """
    seen: set[str] = set()
    unique: list[T] = []
    for candidate in candidates:
        key = normalize_candidate_content(getattr(candidate, "content", ""))
        if not key or key in seen:
            continue
        seen.add(key)
        unique.append(candidate)
    return unique


def rebuild_candidate(
    candidate: MemoryCandidate,
    *,
    event: UtteranceEvent,
    explicit_remember_request: bool,
    subject_person_id: str | None,
) -> MemoryCandidate:
    """Rebuild one model-proposed candidate with trusted identity fields.

    Every identifier the model may emit is discarded and replaced:
    ``candidate_id`` and ``source_event_id`` come from the program, and the
    subject is resolved from trusted metadata (the speaker, or a *hinted*
    third party only after the caller has verified that person exists).
    Semantic hints (assertion, certainty, topic, evidence) are preserved for
    the consolidation layer, which still decides whether a write is allowed.
    """
    assertion = candidate.assertion_type
    return MemoryCandidate(
        candidate_id=new_id("memc"),
        source_event_id=event.event_id,
        subject_person_id=subject_person_id,
        content=candidate.content.strip(),
        operation=candidate.operation,
        assertion_type=assertion,
        certainty_category=candidate.certainty_category,
        explicit_remember_request=(
            explicit_remember_request or candidate.explicit_remember_request
        ),
        topic=candidate.topic,
        kind=candidate.kind,
        source_evidence_span=candidate.source_evidence_span,
    )


async def prepare_candidates(
    repos,
    event: UtteranceEvent,
    candidates: Iterable[MemoryCandidate],
    *,
    explicit_remember_request: bool = False,
) -> list[MemoryCandidate]:
    """Trust-boundary sanitisation of model-proposed candidates.

    - ids are regenerated by the program;
    - the subject defaults to the speaker (trusted);
    - a model-provided *different* subject is only kept when that person
      actually exists, and downgrades the candidate to a third-party report so
      it can never become an authoritative self-report;
    - blank/duplicate content is dropped.
    """
    prepared: list[MemoryCandidate] = []
    for candidate in candidates:
        hinted = candidate.subject_person_id
        subject_id = event.speaker_person_id
        third_party = False
        if hinted is not None and hinted != event.speaker_person_id:
            # A model-named subject can only ever *restrict* a write. Even an
            # unknown id is treated as a third-party statement, so a broken or
            # fabricated id can never turn it into an authoritative self-report.
            third_party = True
            subject_id = hinted if (await repos.person.get(hinted)) is not None else None

        rebuilt = rebuild_candidate(
            candidate,
            event=event,
            explicit_remember_request=explicit_remember_request,
            subject_person_id=subject_id,
        )
        if third_party and rebuilt.assertion_type in (
            AssertionType.UNKNOWN,
            AssertionType.SELF_REPORT,
            AssertionType.CORRECTION,
        ):
            rebuilt = rebuilt.model_copy(
                update={"assertion_type": AssertionType.THIRD_PARTY_REPORT}
            )
        prepared.append(rebuilt)
    return dedupe_candidates(prepared)
