"""Independent local safety response path (V0.4.2).

A companion's persona, mood and conversational style must never decide how an
imminent-risk statement is answered. This module is a small, deterministic
local path:

- ``assess_safety`` scans the *current* utterance for explicit self-harm or
  imminent harm-to-others language (Chinese and English);
- ``safety_response`` returns a fixed, reviewed reply in the utterance's
  language.

The reply is not generated by the model, is not shaped by the emotion layer,
and does not depend on the persona compiler. It is deliberately plain: it
prioritises immediate safety, names emergency channels without pretending to
contact them, and never claims to remember, to be monitoring, or to be able to
keep the person safe by itself.

This is a narrow floor, not a clinical classifier. A missed colloquial phrasing
is possible; the goal is that obvious, explicit statements are never answered
with persona improvisation or left as a silent WAIT because a model or a quiet
setting deferred.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

SELF_HARM = "SELF_HARM"
DANGER_TO_OTHERS = "DANGER_TO_OTHERS"

# Idioms that contain a self-harm-looking phrase but are not a risk statement.
_SELF_HARM_IDIOMS = re.compile(
    r"(想死你|想死我|想死您|笑死|累死|困死|忙死|热死|冷死|饿死|急死|气死|"
    r"吓死|美死|帅死|香死|甜死|烦死)"
)

_SELF_HARM_ZH = re.compile(
    r"(自杀|自残|自伤|割腕|跳楼|上吊|不想活(?:了|下去)?|活着没(?:有)?意思|"
    r"活不下去|结束(?:自己的)?生命|了结自己|想死|求死|一了百了)"
)

_SELF_HARM_EN = re.compile(
    r"(\bsuicid(?:e|al)\b|\bself[-\s]?harm\b|\bkill(?:ing)?\s+myself\b|"
    r"\bend\s+(?:my|this)\s+life\b|\bwant\s+to\s+die\b|"
    r"\bdon'?t\s+want\s+to\s+live\b|\bunaliv(?:e|ing)\s+myself\b)",
    re.IGNORECASE,
)

_OTHERS_ZH = re.compile(
    r"(杀(?:了)?(?:他|她|你|他们|她们|人)|想杀人|要杀人|砍死|捅死|弄死)"
)
_OTHERS_EN = re.compile(
    r"(\bkill\s+(?:him|her|them|you)\b|\bwant\s+to\s+kill\b|"
    r"\bshoot\s+(?:him|her|them|you)\b|\bstab\s+(?:him|her|them|you)\b)",
    re.IGNORECASE,
)

_CJK = re.compile(r"[一-鿿]")
_LATIN = re.compile(r"[A-Za-z]")


@dataclass(frozen=True)
class SafetyAssessment:
    triggered: bool = False
    category: str = ""
    matched: str = ""

    def as_dict(self) -> dict:
        return {
            "triggered": self.triggered,
            "category": self.category,
        }


def assess_safety(text: str) -> SafetyAssessment:
    """Return a conservative, local assessment of the current utterance."""
    value = str(text or "")
    if not value.strip():
        return SafetyAssessment()

    # Idiomatic "X死我了" phrasing is not a risk statement. Remove it before
    # scanning so "笑死我了" cannot become SELF_HARM.
    scrubbed = _SELF_HARM_IDIOMS.sub("", value)

    match = _SELF_HARM_ZH.search(scrubbed) or _SELF_HARM_EN.search(scrubbed)
    if match:
        return SafetyAssessment(True, SELF_HARM, match.group(0)[:64])

    match = _OTHERS_ZH.search(value) or _OTHERS_EN.search(value)
    if match:
        return SafetyAssessment(True, DANGER_TO_OTHERS, match.group(0)[:64])

    return SafetyAssessment()


def detect_language(text: str) -> str:
    """Return ``zh`` for CJK-dominant text, otherwise ``en``."""
    value = str(text or "")
    cjk = len(_CJK.findall(value))
    latin = len(_LATIN.findall(value))
    return "zh" if cjk >= max(1, latin) else "en"


