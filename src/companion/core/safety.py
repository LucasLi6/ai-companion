def safety_response(category: str, language: str) -> str:
    """Return the fixed local reply for a category and language."""
    table = (
        _DANGER_REPLIES if category == DANGER_TO_OTHERS else _SELF_HARM_REPLIES
    )
    return table.get(language) or table["zh"]
